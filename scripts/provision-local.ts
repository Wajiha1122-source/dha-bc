import 'dotenv/config';
import { randomBytes } from 'node:crypto';
import argon2 from 'argon2';
import { pool, transaction, audit } from '../server/db';

// Explicit local operator provisioning. No password is written to any file.
const temporaryPassword = 'Dha!9' + randomBytes(18).toString('base64url');
try {
  const username = await transaction(async db => {
    await db.query('SELECT pg_advisory_xact_lock(810182027)');
    const { rows } = await db.query("SELECT id,username FROM bc.users WHERE role='Administrator' AND active AND must_change_password ORDER BY created_at LIMIT 1 FOR UPDATE");
    const hash = await argon2.hash(temporaryPassword, { type: argon2.argon2id });
    if (rows[0]) {
      await db.query('UPDATE bc.users SET password_hash=$1 WHERE id=$2', [hash, rows[0].id]);
      await db.query("DELETE FROM bc.session WHERE sess->>'userId'=$1", [rows[0].id]);
      await audit(db, rows[0].id, 'Initial administrator credentials regenerated by local operator', null);
      return rows[0].username;
    }
    const name = 'admin.' + randomBytes(4).toString('hex');
    const result = await db.query("INSERT INTO bc.users(username,name,role,password_hash) VALUES($1,'System Administrator','Administrator',$2) RETURNING id", [name, hash]);
    await audit(db, result.rows[0].id, 'Administrator provisioned by local operator', null);
    return name;
  });
  process.stdout.write(JSON.stringify({ username, temporaryPassword }) + '\n');
} catch {
  console.error('Administrator provisioning failed. No credentials were displayed.');
  process.exitCode = 1;
} finally {
  await pool.end();
}
